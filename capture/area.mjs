import { chromium } from 'playwright';
import { readFile } from 'node:fs/promises';
import { PNG } from 'pngjs';
import path from 'node:path';
import * as P from './profile.mjs';
import { serve } from './lib-server.mjs';
const { server, port } = await serve(path.resolve('..'));
const b = await chromium.launch();
const ctx = await b.newContext(P.contextOptions(P.VIEWPORTS[0], 1));
for (const s of P.initScripts()) await ctx.addInitScript({ content: s });
const page = await ctx.newPage();
await page.clock.setFixedTime(new Date(P.FAKE_CLOCK_ISO));
await page.goto(`http://127.0.0.1:${port}/index.html?fidelity=1`, { waitUntil: 'load' });
await page.evaluate(() => document.fonts.ready);
await P.scrollAndSettle(page); await page.evaluate(()=>window.scrollTo(0,0)); await P.freeze(page);
await page.waitForTimeout(300);
const mine = PNG.sync.read(await page.locator('#pdp-above-the-fold').screenshot());
const ref = PNG.sync.read(await readFile('../capture/reference/1440x900/dpr-1/section-03-above-the-fold.png'));
const px=(p,x,y)=>{const i=((p.width*y+x)<<2);return [p.data[i],p.data[i+1],p.data[i+2]];};
const rows=[];
const area=(x0,y0,x1,y1,label)=>{let d=0,n=0;
  for(let y=y0;y<y1;y+=2) for(let x=x0;x<x1;x+=2){const a=px(ref,x,y),c=px(mine,x,y);
    if(Math.abs(a[0]-c[0])+Math.abs(a[1]-c[1])+Math.abs(a[2]-c[2])>30) d++; n++;}
  const px_total=(x1-x0)*(y1-y0);
  rows.push({label, pct:100*d/n, contrib:100*(d/n)*px_total/(1440*1836)});
};
area(0,1,990,120,'gallery: heading');
area(0,120,990,320,'gallery: award badges');
area(0,320,990,930,'gallery: photo+overlays');
area(0,930,990,1580,'left: black area');
area(0,1580,1440,1680,'cookie banner');
area(1000,1,1435,300,'buy: title/rating/usps');
area(1000,300,1435,640,'buy: upgrades');
area(1000,640,1435,860,'buy: sizes');
area(1000,860,1435,1130,'buy: price+ATC');
area(1000,1130,1435,1350,'buy: fine+bundle head');
area(1000,1350,1435,1470,'buy: bundle items');
area(1000,1470,1435,1620,'buy: trust row');
area(1000,1620,1435,1836,'buy: concierge');
area(1150,660,1440,745,'chat bubble');
rows.sort((a,b)=>b.contrib-a.contrib);
console.log('region                        %differ   contribution to total');
for(const r of rows) console.log('  '+r.label.padEnd(28)+r.pct.toFixed(1).padStart(6)+'%   '+r.contrib.toFixed(2).padStart(6)+' pp');
console.log('\n  sum of contributions: '+rows.reduce((s,r)=>s+r.contrib,0).toFixed(2)+' pp');
await b.close(); server.close();
